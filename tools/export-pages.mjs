import { access, cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = join(root, 'site');
const marker = join(target, '.churchtimes-generated');
try {
  await access(target);
  try { await access(marker); } catch { throw new Error('Refusing to overwrite an existing site/ folder without the generated-export marker.'); }
  await rm(target, { recursive: true });
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
const html = await readFile(join(root, 'dist/index.html'), 'utf8');
if (!html.includes('./site/assets/') || html.includes('src="/src/main.js"')) throw new Error('The build is not a compiled Pages export.');
await cp(join(root, 'dist/site'), target, { recursive: true });
await writeFile(marker, 'Generated by npm run export:pages. Edit src/ and public/, then regenerate.\n');
await writeFile(join(root, 'index.html'), html);
await writeFile(join(root, '.nojekyll'), '');
console.log('Exported compiled index.html and site/ for the existing main-branch Pages source.');
