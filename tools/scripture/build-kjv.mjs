// Converts the public-domain King James Version (1769 standard text) from eBible.org's
// verse-per-line file (eng-kjv_vpl.txt, https://ebible.org/Scriptures/eng-kjv_vpl.zip, "Public Domain")
// into per-book JSON under public/scripture/kjv/ and the chapter/verse index in
// src/features/growth/scripture/canon.js. Offline only: pass the extracted .txt path; nothing is fetched.
//   node tools/scripture/build-kjv.mjs <path-to-eng-kjv_vpl.txt>
// Only the 66 books of the Protestant canon are kept (the Apocrypha is dropped). eBible marks words the
// translators supplied in [brackets] (italics in print) and paragraph starts with a pilcrow; both marks are
// removed, the words themselves are kept.
import {readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {BOOKS} from '../../src/features/growth/scripture/books.js';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const source=process.argv[2];
if(!source)throw new Error('Usage: node tools/scripture/build-kjv.mjs <eng-kjv_vpl.txt>');
const byCode=new Map(BOOKS.map(book=>[book.vpl,book]));
const chapters=new Map(BOOKS.map(book=>[book.id,[]]));
const clean=text=>text.replace(/¶/g,'').replace(/[[\]]/g,'').replace(/\s+/g,' ').trim();
for(const line of (await readFile(source,'utf8')).split(/\r?\n/)) {
  const match=line.match(/^([1-4A-Z]{3}) (\d+):(\d+) (.*)$/);
  if(!match)continue;
  const book=byCode.get(match[1]);
  if(!book)continue; // Apocrypha
  const chapter=Number(match[2]),verse=Number(match[3]),text=clean(match[4]);
  const list=chapters.get(book.id);
  list[chapter-1] ||= [];
  if(list[chapter-1].length!==verse-1)throw new Error(`Out-of-order verse ${match[1]} ${chapter}:${verse}`);
  if(!text)throw new Error(`Empty verse ${match[1]} ${chapter}:${verse}`);
  list[chapter-1].push(text);
}
const out=resolve(root,'public/scripture/kjv');
await rm(out,{recursive:true,force:true});
await mkdir(out,{recursive:true});
const counts=[];
let total=0;
for(const book of BOOKS) {
  const list=chapters.get(book.id);
  if(!list.length || list.some(chapter=>!chapter?.length))throw new Error(`Missing chapters for ${book.id}`);
  await writeFile(resolve(out,`${book.id}.json`),JSON.stringify(list)+'\n');
  counts.push(list.map(chapter=>chapter.length));
  total+=list.reduce((sum,chapter)=>sum+chapter.length,0);
}
if(total!==31102)throw new Error(`Expected 31,102 verses in the 66-book KJV, found ${total}`);
await writeFile(resolve(root,'src/features/growth/scripture/canon.js'),
  `// Generated by tools/scripture/build-kjv.mjs. Verses per chapter for each book in BOOKS order (KJV versification).\nexport const VERSE_COUNTS=${JSON.stringify(counts)};\n`);
process.stdout.write(`Wrote ${BOOKS.length} books, ${total} verses.\n`);
